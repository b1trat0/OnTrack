/**
 * One-off maintenance script: download the three self-hosted families used by
 * the theme system and generate apps/web/src/fonts.css with local URLs.
 *
 * Usage: node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const FAMILIES =
  'family=DM+Sans:ital,wght@0,400..700;1,400..700&family=Outfit:wght@500..700&family=JetBrains+Mono:wght@500..700'
const CSS_URL = `https://fonts.googleapis.com/css2?${FAMILIES}&display=swap`
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36'
const fontDir = join('apps', 'web', 'src', 'assets', 'fonts')

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text()
const blocks = [...css.matchAll(/@font-face\s*\{[^}]+\}/g)].map((match) => match[0])
if (blocks.length === 0) throw new Error('No @font-face blocks returned by Google Fonts')

await mkdir(fontDir, { recursive: true })

const faces = []
for (const [index, block] of blocks.entries()) {
  const source = block.match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/)?.[1]
  const family = block.match(/font-family:\s*'([^']+)'/)?.[1]
  const style = block.match(/font-style:\s*([^;]+)/)?.[1]?.trim() ?? 'normal'
  const weight = block.match(/font-weight:\s*([^;]+)/)?.[1]?.trim() ?? '400'
  const range = block.match(/unicode-range:\s*([^;]+)/)?.[1]?.trim()
  if (!source || !family) continue

  const filename = `${family.toLowerCase().replace(/\s+/g, '-')}-${style}-${weight.replace(/\s+/g, '-')}-${index}.woff2`
  const response = await fetch(source)
  if (!response.ok) throw new Error(`Failed to download ${source}: ${response.status}`)
  await writeFile(join(fontDir, filename), Buffer.from(await response.arrayBuffer()))

  faces.push(
    [
      '@font-face {',
      `  font-family: '${family}';`,
      `  font-style: ${style};`,
      `  font-weight: ${weight};`,
      '  font-display: swap;',
      `  src: url('./assets/fonts/${filename}') format('woff2');`,
      range ? `  unicode-range: ${range};` : null,
      '}',
    ]
      .filter(Boolean)
      .join('\n')
  )
}

const header = '/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n\n'
await writeFile(join('apps', 'web', 'src', 'fonts.css'), header + faces.join('\n\n') + '\n')
console.log(`Wrote ${faces.length} @font-face rules and downloaded ${faces.length} WOFF2 files.`)
